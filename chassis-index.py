#!/usr/bin/env python3
"""The rack builder's catalog sizes, from the vendored build.

Every device's RU, depth and configurations, distilled from
assets/dist/<name>.configs.json into site/rack/chassis.json - small enough for
the catalog to load at once, so it can gray out what will not fit without
fetching 158 index files. Regenerated by refresh-assets.sh after every sync;
check-contract.py fails when it is stale.

    ./chassis-index.py          write site/rack/chassis.json
"""
import json
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIST = HERE / "assets" / "dist"
OUT = HERE / "site" / "rack" / "chassis.json"
RU = 44.45


def marked(path):
    """The ids a route can pass through on one compiled face: elements carrying
    `data-guide` (a ring on a component, a duct rect) and pass-throughs
    (`data-class="pass"`). Empty until upstream's guides and passes land."""
    if not path.is_file():
        return [], []
    root = ET.parse(path).getroot()
    guides = sorted({e.get("id") for e in root.iter() if e.get("data-guide") and e.get("id")})
    passes = sorted({e.get("id") for e in root.iter() if e.get("data-class") == "pass" and e.get("id")})
    return guides, passes


def build():
    devices = json.loads((DIST / "devices.json").read_text())["devices"]
    out = {}
    for d in sorted(devices, key=lambda d: d["name"]):
        p = DIST / f"{d['name']}.configs.json"
        if not p.is_file():
            continue
        idx = json.loads(p.read_text())
        c = idx.get("chassis") or {}
        # a stated 0 (a zero-U part's face) is a height, not a missing one
        h = c.get("h") if c.get("h") is not None else RU
        out[d["name"]] = {
            "manufacturer": d.get("manufacturer"),
            "model": d.get("model") or d["name"],
            "family": (d.get("portfolio") or {}).get("family"),
            # chassis.ru when the index states it - 0 included, which is a
            # zero-U part - else the height in mm, as rack.js's unitsOf reads it
            "ru": c["ru"] if c.get("ru") is not None else max(1, round(h / RU)),
            "h": h, "w": c.get("w"), "d": c.get("d"), "airflow": c.get("airflow"),
            "default": idx.get("default"),
            "configs": [x["name"] for x in idx.get("configs", [])],
        }
        # only a stated mount other than a rack's, so the file barely grows
        if c.get("mount") and c["mount"] != "rack":
            out[d["name"]]["mount"] = c["mount"]
        # a sheet body (rack3d.js hides its box), the vendor's stated cable
        # capacity, and the ids a route can pass through (spec §3): each only
        # when the device has it, so the file barely grows
        entry = out[d["name"]]
        if c.get("shell"):
            entry["shell"] = c["shell"]
        perf = (idx.get("attrs") or {}).get("performance") or {}
        if perf.get("cable-capacity") is not None:
            entry["capacity"] = {"count": perf["cable-capacity"], "basis": perf.get("cable-capacity-basis", "")}
        for view in ("front", "rear"):
            g, p = marked(DIST / f"{d['name']}.{idx.get('default')}.{view}.svg")
            if g:
                entry.setdefault("guides", {})[view] = g
            if p:
                entry.setdefault("passes", {})[view] = p
    return {"generated-from": "assets/dist/devices.json and <name>.configs.json, by chassis-index.py",
            "devices": out}


def text():
    return json.dumps(build(), indent=1, sort_keys=True) + "\n"


if __name__ == "__main__":
    OUT.write_text(text())
    print(f"chassis-index: {len(build()['devices'])} devices -> {OUT.relative_to(HERE)}")
